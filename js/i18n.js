let currentLanguage = localStorage.getItem("roadfix_lang") || "en";

function setLanguage(lang) {
  if (translations[lang]) {
    currentLanguage = lang;
    localStorage.setItem("roadfix_lang", lang);
    applyTranslations();
    document.dispatchEvent(new CustomEvent("roadfix:languageChanged", { detail: { lang } }));
  }
}

function t(key) {
  const dict = translations[currentLanguage] || translations.en;
  return dict[key] || translations.en[key] || key;
}

function applyTranslations() {
  const elements = document.querySelectorAll("[data-i18n]");
  elements.forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (key) {
      const translated = t(key);
      if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
        if (el.hasAttribute("placeholder")) {
          el.setAttribute("placeholder", translated);
        }
      } else {
        el.textContent = translated;
      }
    }
  });

  // Also update select option values or titles if needed
  const langSelect = document.getElementById("lang-select");
  if (langSelect && langSelect.value !== currentLanguage) {
    langSelect.value = currentLanguage;
  }
}

// Export to window for global modular access
window.i18n = {
  currentLanguage,
  setLanguage,
  t,
  applyTranslations,
  translations
};
